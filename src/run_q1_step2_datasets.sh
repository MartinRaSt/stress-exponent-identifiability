# Q1 step 2 (reserse/2026-09-14_specifikace_rozsireni_q1.md, A.9 - "Run
# order", item 2) - chain of steps for the regime L hold-out candidates, AFTER
# `src/run_screen_regime_candidates.sh full` has already run and the author
# has confirmed the list of eligible ones (step 1, run SEPARATELY BEFORE this
# script):
#   1. dataset_properties --datasets holdout   (K1 on the hold-out set)
#   2. exp1_dr_benchmark --datasets holdout --tier tier1  (15 main methods)
#   3. exp6_alpha_curves --datasets holdout    (alpha curves on the hold-out set)
#   4. exp1_dr_benchmark --datasets holdout --tier tier2  (6 remaining methods)
#   5. exp1_cluster_geometry                   (recompute over ALL saved embeddings)
#   6. fit_alpha_rule --full                    (check agreement with the frozen rule, A.5)
#   7. exp1_regime_stratified                   (update the stratified table)
#   8. exp1_holdout_confirmatory                (F_A1-F_A7)
#   9. power_analysis_regime                    (A.7)
#  10. fig_holdout_paired, fig_regime_map        (figures)
#  11. run_main.sh full --no-figures            (statistics/tables/macros, WITHOUT figures
#                                                  - those are already generated by step 10 + make_figures.sh)
#
# Each step, on error, STOPS the following steps (they depend on each other - resume/
# checkpoint ensures already completed combinations are not recomputed).
# Parameter: full (default) | quick | smoke. Sleep is disabled by
# each called run_*.sh itself (no_sleep.sh), here additionally for the whole chain.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

source "$ROOT/src/common/no_sleep.sh"
sammon_no_sleep_reexec "$0" "$@"

PYTHON="${PYTHON:-$ROOT/venv/bin/python}"
if [ ! -x "$PYTHON" ]; then
    echo "ERROR: project venv Python interpreter not found: $PYTHON" >&2
    echo "Set the PYTHON environment variable to the project's venv Python path, e.g.:" >&2
    echo "  PYTHON=/path/to/venv/bin/python $0 $*" >&2
    exit 1
fi

MODE="${1:-full}"
LOGDIR="results/logs"
mkdir -p "$LOGDIR"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] run_q1_step2_datasets start (mode=$MODE)" >> "$LOGDIR/run_q1_step2_datasets.log"

RC1=""; RC2=""; RC3=""; RC4=""; RC5=""; RC6=""; RC7=""; RC8=""; RC9=""; RC10A=""; RC10B=""; RC11=""

echo "=== 1/11 dataset_properties --datasets holdout ==="
if "$PYTHON" -m src.experiments.dataset_properties --"$MODE" --datasets holdout; then
    RC1=0
else
    RC1=$?
    echo "ERROR: dataset_properties finished with code $RC1 - stopping."
fi

if [ "$RC1" = "0" ]; then
    echo "=== 2/11 exp1_dr_benchmark --datasets holdout --tier tier1 ==="
    if "$PYTHON" -m src.experiments.exp1_dr_benchmark --"$MODE" --datasets holdout --tier tier1; then
        RC2=0
    else
        RC2=$?
        echo "ERROR: exp1_dr_benchmark (tier1) finished with code $RC2 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ]; then
    echo "=== 3/11 exp6_alpha_curves --datasets holdout ==="
    if "$PYTHON" -m src.experiments.exp6_alpha_curves --"$MODE" --datasets holdout; then
        RC3=0
    else
        RC3=$?
        echo "ERROR: exp6_alpha_curves finished with code $RC3 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ] && [ "$RC3" = "0" ]; then
    echo "=== 4/11 exp1_dr_benchmark --datasets holdout --tier tier2 ==="
    if "$PYTHON" -m src.experiments.exp1_dr_benchmark --"$MODE" --datasets holdout --tier tier2; then
        RC4=0
    else
        RC4=$?
        echo "ERROR: exp1_dr_benchmark (tier2) finished with code $RC4 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ] && [ "$RC3" = "0" ] && [ "$RC4" = "0" ]; then
    echo "=== 5/11 exp1_cluster_geometry ==="
    if "$ROOT/src/run_exp1_cluster_geometry.sh" "$MODE"; then
        RC5=0
    else
        RC5=$?
        echo "ERROR: exp1_cluster_geometry finished with code $RC5 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ] && [ "$RC3" = "0" ] && [ "$RC4" = "0" ] && [ "$RC5" = "0" ]; then
    echo "=== 6/11 fit_alpha_rule --full (check agreement with the frozen rule) ==="
    if "$ROOT/src/run_fit_alpha_rule.sh" "$MODE"; then
        RC6=0
    else
        RC6=$?
        echo "ERROR: fit_alpha_rule finished with code $RC6 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ] && [ "$RC3" = "0" ] && [ "$RC4" = "0" ] && [ "$RC5" = "0" ] && [ "$RC6" = "0" ]; then
    echo "=== 7/11 exp1_regime_stratified ==="
    if "$ROOT/src/run_exp1_regime_stratified.sh" "$MODE"; then
        RC7=0
    else
        RC7=$?
        echo "ERROR: exp1_regime_stratified finished with code $RC7 - stopping."
    fi
fi

if [ "$RC1" = "0" ] && [ "$RC2" = "0" ] && [ "$RC3" = "0" ] && [ "$RC4" = "0" ] && [ "$RC5" = "0" ] && [ "$RC6" = "0" ] && [ "$RC7" = "0" ]; then
    echo "=== 8/11 exp1_holdout_confirmatory ==="
    if "$ROOT/src/run_exp1_holdout_confirmatory.sh" "$MODE"; then
        RC8=0
    else
        RC8=$?
        echo "ERROR: exp1_holdout_confirmatory finished with code $RC8 - stopping."
    fi
fi

echo "=== 9/11 power_analysis_regime ==="
if "$ROOT/src/run_power_analysis_regime.sh" "$MODE"; then RC9=0; else RC9=$?; fi

echo "=== 10/11 fig_holdout_paired, fig_regime_map ==="
if "$PYTHON" -m src.figures.fig_holdout_paired --"$MODE"; then RC10A=0; else RC10A=$?; fi
if "$PYTHON" -m src.figures.fig_regime_map --"$MODE"; then RC10B=0; else RC10B=$?; fi

echo "=== 11/11 run_main.sh $MODE --no-figures ==="
if "$ROOT/src/run_main.sh" "$MODE" --no-figures; then RC11=0; else RC11=$?; fi

echo "============================================================"
echo "run_q1_step2_datasets (mode=$MODE) summary:"
echo "  1 dataset_properties (holdout)       : $RC1"
echo "  2 exp1_dr_benchmark (tier1)          : $RC2"
echo "  3 exp6_alpha_curves (holdout)        : $RC3"
echo "  4 exp1_dr_benchmark (tier2)          : $RC4"
echo "  5 exp1_cluster_geometry              : $RC5"
echo "  6 fit_alpha_rule                     : $RC6"
echo "  7 exp1_regime_stratified             : $RC7"
echo "  8 exp1_holdout_confirmatory          : $RC8"
echo "  9 power_analysis_regime              : $RC9"
echo " 10 figures (holdout_paired,regime_map): $RC10A/$RC10B"
echo " 11 run_main --no-figures              : $RC11"
echo "[$(date '+%Y-%m-%d %H:%M:%S')] run_q1_step2_datasets done" >> "$LOGDIR/run_q1_step2_datasets.log"
