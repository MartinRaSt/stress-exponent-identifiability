# Runs the CPU vs GPU dense SMACOF timing benchmark (see
# src/sammon/gpu_dense_timing.py, sections 12.1/12.5 of the specification).
# Resumable - a repeated run skips already completed (n, device) combinations.
#
# WARNING (Linux/macOS): the GPU part requires a CUDA build of torch (the project uses
# torch cu126 on an RTX 3070 Ti) - on a machine without an NVIDIA GPU/drivers only the
# CPU part will run, the rest is skipped/fails fail-loud depending on the script's configuration.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Disable computer standby/hibernation for the duration of the run (systemd-inhibit, see
# src/common/no_sleep.sh) - author requirement.
source "$ROOT/src/common/no_sleep.sh"
sammon_no_sleep_reexec "$0" "$@"

PYTHON="${PYTHON:-$ROOT/venv/bin/python}"
if [ ! -x "$PYTHON" ]; then
    echo "ERROR: project venv Python interpreter not found: $PYTHON" >&2
    echo "Set the PYTHON environment variable to the project's venv Python path, e.g.:" >&2
    echo "  PYTHON=/path/to/venv/bin/python $0 $*" >&2
    exit 1
fi

"$PYTHON" -m src.sammon.gpu_dense_timing
