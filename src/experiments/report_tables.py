def write_exp4_relative_table(mode: str, logger) -> Path | None:
    """results/tables/[<mode>/]exp4_relative_table.csv/.tex - median and IQR
    over datasets of the percentage change of stability (displacement) and
    quality (stress) vs. lambda=0, for each (solver, lambda) from
    results/data/[<mode>/]exp4_relative.csv (K9)."""
    rel_path = get_mode_path("results_data_dir", mode) / "exp4_relative.csv"
    if not rel_path.exists():
        logger.warning("E4 relative table: %s does not exist, skipping.", rel_path)
        return None
    rel = pd.read_csv(rel_path)
    needed = ["solver", "lam", "stab_pct_change_vs_lambda0", "qual_pct_change_vs_lambda0", "dataset"]
    missing = [c for c in needed if c not in rel.columns]
    if missing:
        raise KeyError(f"{rel_path} is missing columns {missing}.")
    g = rel.groupby(["solver", "lam"])
    table = pd.DataFrame({
        "n_datasets": g["dataset"].nunique(),
        "stab_pct_change_median": g["stab_pct_change_vs_lambda0"].median(),
        "stab_pct_change_iqr": g["stab_pct_change_vs_lambda0"].quantile(0.75) - g["stab_pct_change_vs_lambda0"].quantile(0.25),
        "qual_pct_change_median": g["qual_pct_change_vs_lambda0"].median(),
        "qual_pct_change_iqr": g["qual_pct_change_vs_lambda0"].quantile(0.75) - g["qual_pct_change_vs_lambda0"].quantile(0.25),
    }).reset_index().sort_values(["solver", "lam"]).reset_index(drop=True)

    tables_dir = get_tables_dir(mode)
    out_csv = tables_dir / f"{EXP4_RELATIVE_TABLE}.csv"
    table.to_csv(out_csv, index=False)
    write_booktabs_tex(
        table, tables_dir / f"{EXP4_RELATIVE_TABLE}.tex",
        caption="E4: relative change (\\%) of temporal displacement (stability) and stress (quality) vs. lambda = 0, median and IQR over datasets",
        label=f"tab:{EXP4_RELATIVE_TABLE}", float_format="%.2f",
        comment_lines=["source: results/data/exp4_relative.csv (exp4_temporal.py, K9); a negative stability change = smaller displacement (better), a negative quality change = lower stress (better)"],
    )
    logger.info("E4 relative table written: %s (%d rows).", out_csv, table.shape[0])
    return out_csv


