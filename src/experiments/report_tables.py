def write_booktabs_tex(
    df: pd.DataFrame, out_path: Path, caption: str, label: str, float_format: str = "%.4f",
    comment_lines: list[str] | None = None, bold_mask: pd.DataFrame | None = None,
) -> None:
    """Writes a booktabs LaTeX table (\\input-able). `comment_lines` are
    inserted as `%` comments below the header (provenance, notes),
    `bold_mask` (same shape as df, bool) highlights the best values."""
    cols = list(df.columns)
    lines = ["% auto-generated by src/main.py (src/experiments/report_tables.py) - do not edit by hand"]
    for c in comment_lines or []:
        lines.append(f"% {c}")
    lines += [
        "\\begin{table}[htbp]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{'l' * len(cols)}}}", "\\toprule",
        " & ".join(c.replace("_", "\\_") for c in cols) + " \\\\", "\\midrule",
    ]
    for i, (_, row) in enumerate(df.iterrows()):
        cells = []
        for j, v in enumerate(row):
            if isinstance(v, (float, np.floating)):
                cell = "--" if not np.isfinite(v) else float_format % v
            else:
                cell = str(v).replace("_", "\\_")
            if bold_mask is not None and bool(bold_mask.iloc[i, j]):
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _load_ok_results(base_experiment_name: str, mode: str, logger) -> pd.DataFrame | None:
    csv_path = results_csv_path(resolve_experiment_name(base_experiment_name, mode))
    if not csv_path.exists():
        logger.warning("Table %s: %s does not exist, skipping.", base_experiment_name, csv_path)
        return None
    df = pd.read_csv(csv_path)
    ok = df[df["status"] == _STATUS_OK]
    if ok.empty:
        logger.warning("Table %s: no 'ok' rows in %s, skipping.", base_experiment_name, csv_path)
        return None
    return ok


def method_summary(ok: pd.DataFrame, metrics: dict[str, str], unit_col: str = "dataset") -> pd.DataFrame:
    """For each metric: median over seeds at (unit, method), then median and
    IQR over units and the average method rank (1 = best):
      `<metric>_avg_rank` - the rank in EACH unit among the methods that
        have a value in it (descriptive; units with a missing method, e.g.
        'skipped_max_n' on large graphs, are NOT excluded - number of units
        `<metric>_n_units`);
      `<metric>_avg_rank_complete` - only over COMPLETE blocks (same
        convention as `stats.friedman_nemenyi`; number of blocks
        `<metric>_n_units_complete`).
    Returns a DataFrame indexed by method."""
    out: dict[str, pd.Series] = {}
    for metric, direction in metrics.items():
        if metric not in ok.columns:
            continue
        sub = ok[ok[metric].notna()]
        if sub.empty:
            continue
        wide = sub.groupby([unit_col, "method"])[metric].median().unstack("method")
        out[f"{metric}_median"] = wide.median(axis=0)
        out[f"{metric}_iqr"] = wide.quantile(0.75, axis=0) - wide.quantile(0.25, axis=0)
        out[f"{metric}_n_units"] = wide.notna().sum(axis=0)
        # rank within a unit among the available methods (NaN is ignored)
        out[f"{metric}_avg_rank"] = wide.rank(axis=1, ascending=(direction != "max"), method="average").mean(axis=0)
        complete = wide.dropna(axis=0, how="any")
        if complete.shape[0] >= 1 and complete.shape[1] >= 2:
            source = -complete.to_numpy(dtype=np.float64) if direction == "max" else complete.to_numpy(dtype=np.float64)
            ranks = rankdata(source, axis=1, method="average").mean(axis=0)
            out[f"{metric}_avg_rank_complete"] = pd.Series(ranks, index=complete.columns)
            out[f"{metric}_n_units_complete"] = pd.Series(complete.shape[0], index=complete.columns)
    if not out:
        return pd.DataFrame()
    return pd.DataFrame(out)


def _best_mask(df: pd.DataFrame, metrics: dict[str, str]) -> pd.DataFrame:
    """A bool mask of the best value in the *_median columns (per direction) and *_avg_rank (min)."""
    mask = pd.DataFrame(False, index=df.index, columns=df.columns)
    for metric, direction in metrics.items():
        col = f"{metric}_median"
        if col in df.columns and df[col].notna().any():
            best = df[col].max() if direction == "max" else df[col].min()
            mask[col] = df[col] == best
        col = f"{metric}_avg_rank"
        if col in df.columns and df[col].notna().any():
            mask[col] = df[col] == df[col].min()
    return mask


def _table_columns(metrics: dict[str, str], df: pd.DataFrame) -> list[str]:
    cols = []
    for metric in metrics:
        for suffix in ("_median", "_avg_rank"):
            if f"{metric}{suffix}" in df.columns:
                cols.append(f"{metric}{suffix}")
    return cols


