def write_exp1_main_table(mode: str, logger) -> Path | None:
    """results/tables/[<mode>/]exp1_main_table.csv/.tex - methods from
    `report.main_methods` x metrics from `report.main_table_metrics`. Also
    runs Friedman/Nemenyi ONLY over main_methods (k <= 20, avoids the
    q_alpha WARNING for k=21) -> results/data/[<mode>/]stats_exp1_dr_benchmark_main_<metric>.csv."""
    cfg = load_experiments_config()
    main_methods: list[str] = cfg["report"]["main_methods"]
    metrics: dict[str, str] = cfg["report"]["main_table_metrics"]
    cluster_metrics: list[str] = cfg["report"]["main_table_cluster_geometry_metrics"]
    primary_metrics: dict[str, str] = cfg["stats"]["primary_metrics"]

    ok = _load_ok_results("exp1_dr_benchmark", mode, logger)
    if ok is None:
        return None
    missing = [m for m in main_methods if m not in set(ok["method"])]
    if missing:
        logger.warning("E1 main table: methods from report.main_methods without an 'ok' row in E1: %s.", missing)
    main = ok[ok["method"].isin(main_methods)].copy()
    if main.empty:
        logger.warning("E1 main table: none of report.main_methods are in the E1 CSV, skipping.")
        return None

    # cluster-geometry metrics (K10) from exp1_cluster_geometry_results.csv -
    # the E1 CSV only has them for methods added after evaluate() was
    # extended (densmap, phate, alpha_pred); cluster_geometry has them for
    # all methods -> the single source
    cg = _load_ok_results("exp1_cluster_geometry", mode, logger)
    base_metrics = {k: v for k, v in metrics.items() if k not in cluster_metrics}
    summary = method_summary(main, base_metrics)
    if cg is not None:
        cg_main = cg[cg["method"].isin(main_methods)]
        cg_metrics = {k: v for k, v in metrics.items() if k in cluster_metrics}
        cg_summary = method_summary(cg_main, cg_metrics)
        summary = summary.join(cg_summary, how="left")
    else:
        logger.warning("E1 main table: exp1_cluster_geometry is missing - columns %s omitted.", cluster_metrics)
    if summary.empty:
        logger.warning("E1 main table: no metric available, skipping.")
        return None

    order_col = next((f"{m}_avg_rank" for m in metrics if f"{m}_avg_rank" in summary.columns), None)
    summary = summary.reindex([m for m in main_methods if m in summary.index])
    if order_col is not None:
        summary = summary.sort_values(order_col)
    table = summary.reset_index().rename(columns={"index": "method"})
    cols = ["method"] + _table_columns(metrics, table)
    table = table[cols]

    tables_dir = get_tables_dir(mode)
    out_csv = tables_dir / f"{EXP1_MAIN_TABLE}.csv"
    summary.reset_index().rename(columns={"index": "method"}).to_csv(out_csv, index=False)
    mask = _best_mask(table.set_index("method"), metrics).reset_index(drop=True)
    mask.insert(0, "method", False)
    n_datasets = int(main["dataset"].nunique())
    write_booktabs_tex(
        table, tables_dir / f"{EXP1_MAIN_TABLE}.tex",
        caption=f"E1: main methods (median over seeds, then over {n_datasets} datasets; avg. rank 1 = best)",
        label=f"tab:{EXP1_MAIN_TABLE}",
        comment_lines=[
            "source: results/data/exp1_dr_benchmark_results.csv + exp1_cluster_geometry_results.csv (cluster-geometry metrics)",
            f"methods: config_experiments.yaml report.main_methods ({len(main_methods)}); metrics: report.main_table_metrics",
            "avg_rank = average rank of the method within a dataset (among methods with a value); a complete-blocks-only variant is in the CSV (*_avg_rank_complete)",
        ],
        bold_mask=mask,
    )
    logger.info("E1 main table written: %s (%d methods, %d datasets).", out_csv, table.shape[0], n_datasets)

    # Friedman/Nemenyi only over main_methods (primary metrics)
    for metric, direction in primary_metrics.items():
        run_stats_for_experiment("exp1_dr_benchmark", metric, direction, logger, df=main, output_suffix="_main", mode=mode)
    return out_csv


