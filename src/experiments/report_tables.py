def exp5_init_equivalence(ok: pd.DataFrame, a: str, b: str) -> pd.DataFrame:
    """A numeric check of agreement between two inits: paired rows (dataset,
    alpha, eps_D_q, seed) -> max |diff| and median |diff| for the EXP5_METRICS."""
    left = ok[ok["init"] == a].set_index(EXP5_MERGE_KEYS)
    right = ok[ok["init"] == b].set_index(EXP5_MERGE_KEYS)
    common = left.index.intersection(right.index)
    rows = []
    for metric in EXP5_METRICS:
        diff = (left.loc[common, metric] - right.loc[common, metric]).abs()
        rows.append({
            "init_a": a, "init_b": b, "metric": metric, "n_pairs": int(diff.notna().sum()),
            "max_abs_diff": float(diff.max()) if diff.notna().any() else np.nan,
            "median_abs_diff": float(diff.median()) if diff.notna().any() else np.nan,
        })
    return pd.DataFrame(rows)


def write_exp5_factorial_summary(mode: str, logger) -> Path | None:
    """results/tables/[<mode>/]exp5_factorial_summary.csv/.tex - the main
    effects of the init / eps_D_q / alpha factors: for each level, median
    over seeds and the other factors per dataset, then median + IQR over
    datasets and the average rank of the levels (complete blocks). A
    descriptive summary, NO Friedman test over 117 combinations (K12c). Init
    'classical_mds' merged with 'pca' (Torgerson); the agreement is verified
    numerically -> exp5_init_equivalence_check.csv + a WARNING on a nonzero
    difference."""
    ok = _load_ok_results("exp5_ablation", mode, logger)
    if ok is None:
        return None
    for col in EXP5_FACTORS:
        if col not in ok.columns:
            raise KeyError(f"exp5_ablation_results.csv has no column '{col}'.")
    ok = ok[ok[list(EXP5_METRICS)].notna().all(axis=1)].copy()
    tables_dir = get_tables_dir(mode)
    tol = float(load_experiments_config()["report"]["exp5_init_merge_tolerance"])

    # check agreement of the merged inits
    equiv_rows = []
    for src_init, dst_init in EXP5_INIT_MERGE.items():
        if src_init in set(ok["init"]) and dst_init in set(ok["init"]):
            eq = exp5_init_equivalence(ok, src_init, dst_init)
            equiv_rows.append(eq)
            for _, r in eq.iterrows():
                within = bool(np.isfinite(r["max_abs_diff"]) and r["max_abs_diff"] <= tol)
                getattr(logger, "info" if within else "warning")(
                    "E5 init %s vs %s: %s max|diff|=%.3g (median %.3g, n=%d paired runs, tolerance %.1e)%s",
                    src_init, dst_init, r["metric"], r["max_abs_diff"], r["median_abs_diff"], r["n_pairs"], tol,
                    " - agreement within tolerance, merged." if within else " - DIFFERENCE ABOVE TOLERANCE, merged anyway (check it).",
                )
    equiv = pd.concat(equiv_rows, ignore_index=True) if equiv_rows else pd.DataFrame(
        columns=["init_a", "init_b", "metric", "n_pairs", "max_abs_diff", "median_abs_diff"])
    equiv.to_csv(tables_dir / f"{EXP5_INIT_EQUIVALENCE}.csv", index=False)
    ok["init"] = ok["init"].replace(EXP5_INIT_MERGE)

    rows: list[dict[str, Any]] = []
    for factor in EXP5_FACTORS:
        per_unit = ok.groupby(["dataset", factor])[list(EXP5_METRICS)].median()
        row_by_level: dict[Any, dict[str, Any]] = {}
        for metric, direction in EXP5_METRICS.items():
            wide = per_unit[metric].unstack(factor)
            complete = wide.dropna(axis=0, how="any")
            ranks = None
            if complete.shape[0] >= 1 and complete.shape[1] >= 2:
                source = -complete.to_numpy(dtype=np.float64) if direction == "max" else complete.to_numpy(dtype=np.float64)
                ranks = dict(zip(complete.columns, rankdata(source, axis=1, method="average").mean(axis=0)))
            for level in wide.columns:
                col = wide[level].dropna()
                r = row_by_level.setdefault(level, {"factor": factor, "level": level, "n_datasets": int(col.shape[0])})
                r[f"median_{metric}"] = float(col.median()) if not col.empty else np.nan
                r[f"iqr_{metric}"] = float(col.quantile(0.75) - col.quantile(0.25)) if not col.empty else np.nan
                r[f"avg_rank_{metric}"] = float(ranks[level]) if ranks is not None and level in ranks else np.nan
                r["n_datasets_complete_block"] = int(complete.shape[0])
        rows.extend(row_by_level.values())
    if not rows:
        return None
    table = pd.DataFrame(rows)
    table["level"] = table["level"].astype(str)
    out_csv = tables_dir / f"{EXP5_FACTORIAL_SUMMARY}.csv"
    table.to_csv(out_csv, index=False)

    comment = [
        "source: results/data/exp5_ablation_results.csv; main effects (median over seeds and the other factors per dataset, then over datasets)",
        "init 'classical_mds' merged with 'pca' (Torgerson: classic MDS over Euclidean D = PCA); numeric agreement check in "
        f"{EXP5_INIT_EQUIVALENCE}.csv",
    ]
    for _, r in equiv.iterrows():
        comment.append(f"check {r['init_a']} vs {r['init_b']}, {r['metric']}: max|diff|={r['max_abs_diff']:.3g}, n={int(r['n_pairs'])}")
    write_booktabs_tex(
        table, tables_dir / f"{EXP5_FACTORIAL_SUMMARY}.tex",
        caption="E5 ablation: main effects of initialisation, epsilon quantile and alpha (descriptive summary; avg. rank 1 = best within factor)",
        label=f"tab:{EXP5_FACTORIAL_SUMMARY}", comment_lines=comment,
    )
