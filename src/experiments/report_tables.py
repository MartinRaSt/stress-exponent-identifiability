def exp3_large_graph_threshold() -> int:
    """The large-graph threshold (number of LCC nodes) from the exp3 config - no magic number."""
    return int(load_experiments_config()["exp3_graph_layout"]["large_graph_threshold_nodes"])


def add_exp3_groups(ok: pd.DataFrame, threshold: int) -> pd.DataFrame:
    """Adds the columns `size_group` ('small' for n_nodes_lcc <= threshold,
    otherwise 'large') and `kind` ('distance' = the dataset contains '__', otherwise 'native')."""
    out = ok.copy()
    out["size_group"] = np.where(out["n_nodes_lcc"] <= threshold, EXP3_SIZE_GROUPS[0], EXP3_SIZE_GROUPS[1])
    out["kind"] = np.where(out["dataset"].str.contains("__", regex=False), EXP3_KIND_GROUPS[0], EXP3_KIND_GROUPS[1])
    return out


def write_exp3_group_tables(mode: str, logger) -> Path | None:
    """results/tables/[<mode>/]exp3_main_table.csv/.tex - rows (kind,
    size_group, method), columns median + avg_rank of the primary metrics
    and time; statistics (Friedman/Nemenyi) separately for each group ->
    results/data/[<mode>/]stats_exp3_graph_layout_<kind>_<size>_<metric>.csv."""
    cfg = load_experiments_config()
    primary_metrics: dict[str, str] = cfg["stats"]["primary_metrics"]
    metrics = dict(primary_metrics)
    metrics["wall_time_sec"] = "min"
    threshold = exp3_large_graph_threshold()

    ok = _load_ok_results("exp3_graph_layout", mode, logger)
    if ok is None:
        return None
    if "n_nodes_lcc" not in ok.columns:
        raise KeyError("exp3_graph_layout_results.csv has no column 'n_nodes_lcc' - cannot split into small/large graphs.")
    ok = add_exp3_groups(ok, threshold)

    pieces = []
    for kind in EXP3_KIND_GROUPS:
        for size_group in EXP3_SIZE_GROUPS:
            sub = ok[(ok["kind"] == kind) & (ok["size_group"] == size_group)]
            if sub.empty:
                logger.warning("E3 table: group %s/%s is empty, skipping.", kind, size_group)
                continue
            summ = method_summary(sub, metrics)
            if summ.empty:
                continue
            summ = summ.reset_index().rename(columns={"index": "method"})
            summ.insert(0, "n_graphs", int(sub["base_graph"].nunique()))
            summ.insert(0, "size_group", size_group)
            summ.insert(0, "kind", kind)
            order_col = f"{next(iter(primary_metrics))}_avg_rank"
            if order_col in summ.columns:
                summ = summ.sort_values(order_col)
            pieces.append(summ)
            for metric, direction in primary_metrics.items():
                run_stats_for_experiment(
                    "exp3_graph_layout", metric, direction, logger, df=sub, output_suffix=f"_{kind}_{size_group}", mode=mode,
                )
    if not pieces:
        return None
    full = pd.concat(pieces, ignore_index=True)

    tables_dir = get_tables_dir(mode)
    out_csv = tables_dir / f"{EXP3_MAIN_TABLE}.csv"
    full.to_csv(out_csv, index=False)
    cols = ["kind", "size_group", "n_graphs", "method"] + _table_columns(metrics, full)
    table = full[cols]
    write_booktabs_tex(
        table, tables_dir / f"{EXP3_MAIN_TABLE}.tex",
        caption=f"E3: graph layouts split into small (n <= {threshold} nodes) and large graphs (median over seeds, then over graphs x distances; avg. rank 1 = best within group)",
        label=f"tab:{EXP3_MAIN_TABLE}",
        comment_lines=[
            "source: results/data/exp3_graph_layout_results.csv; large-graph threshold: config_experiments.yaml exp3_graph_layout.large_graph_threshold_nodes",
            "distance = methods over the distance matrix (unit = graph x distance), native = graph layouts (unit = graph)",
            "avg_rank = average rank within a unit among methods with a value (methods with 'skipped_max_n' on large graphs do not exclude the unit); *_avg_rank_complete in the CSV = complete blocks only (Friedman)",
        ],
    )
    logger.info("E3 group table written: %s (%d rows, threshold=%d).", out_csv, table.shape[0], threshold)
    return out_csv


